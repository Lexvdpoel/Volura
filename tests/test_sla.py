@pytest.mark.parametrize("mx, my, corner", [(False, False, (0, 340)), (True, False, (600, 340)),
                                            (False, True, (0, 0)), (True, True, (600, 0))])
def test_the_plate_maps_to_the_screen_as_prusaslicer_does(mx, my, corner):
    t = ss.image_transform(printer(mx, my))
    p = t.map(QPointF(0.0, 0.0))                       # the front left corner of the plate
    assert (p.x(), p.y()) == pytest.approx(corner)
    q = t.map(QPointF(60.0, 34.0))                     # the middle stays the middle
    assert (q.x(), q.y()) == pytest.approx((300, 170))


@pytest.mark.parametrize("box", [(10, 10, 30, 20), (0, 0, 120, 68), (100, 50, 120, 68), None])
def test_a_layer_png_is_the_image_qt_draws(box):
    pr = printer(True, False)
    t = ss.image_transform(pr)
    polys = []
    if box:
        x0, y0, x1, y1 = box
        polys = [np.array([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], dtype=float),
                 np.array([(x0 + 2, y0 + 2), (x0 + 2, y0 + 4), (x0 + 4, y0 + 4),
                           (x0 + 4, y0 + 2)], dtype=float)]
    img = QImage.fromData(ss.layer_png(polys, pr, t)).convertToFormat(QImage.Format_Grayscale8)
    want = ss.layer_image(polys, pr, t)
    assert (img.width(), img.height()) == (600, 340)
    assert np.array_equal(ss._pixels(img), ss._pixels(want))


def test_an_sl1_archive_has_a_png_per_layer_and_the_profile(library, tmp_path):
    pr = library.printer("Acme Resin Two")
    st = sp.ResinSettings(layer_height=0.1, exposure=2.0, bottom_exposure=20.0, bottom_layers=3)
    cube = ss.place_on_plate([mf.Manifold.cube([10, 10, 2])], pr)
    path = tmp_path / "x.sl1"
    result = ss.write_sl1(str(path), pr, library.print_profile(0.1), st, cube)
    assert result.layers == 20 and result.millilitres == pytest.approx(0.2)
    with zipfile.ZipFile(path) as z:
        names = z.namelist()
        config = z.read("config.ini").decode()
        profile = z.read("prusaslicer.ini").decode()
    assert sum(n.endswith(".png") for n in names) == 20
    assert "expTime = 2" in config and "numFade = 3" in config and "layerHeight = 0.1" in config
    assert "display_pixels_x = 600" in profile and "FILEFORMAT_GOO" in profile
    img = ss.read_layer(path.read_bytes(), 5)
    white = int((ss._pixels(img.convertToFormat(QImage.Format_Grayscale8)) > 127).sum())
    assert white == pytest.approx(50 * 50, rel=0.05), "a 10 mm square is 50 by 50 pixels"


def test_a_print_higher_than_the_printer_is_refused(library, tmp_path):
    pr = library.printer("Acme Resin Two")
    tall = ss.place_on_plate([mf.Manifold.cube([5, 5, 200])], pr)
    with pytest.raises(ValueError):
        ss.write_sl1(str(tmp_path / "x.sl1"), pr, None, sp.ResinSettings(), tall)


# ------------------------------------------------------------------ supports

CFG = su.SupportConfig()


def shapes():
    return {"sphere": mf.Manifold.sphere(10, 48),
            "T": mf.Manifold.cube([4, 4, 20]).translate((-2, -2, 0))
            + mf.Manifold.cube([30, 4, 3]).translate((-15, -2, 20)),
            "plate": mf.Manifold.cube([20, 20, 2])}


@pytest.mark.parametrize("name", ["sphere", "T", "plate"])
def test_a_part_stands_on_supports_and_a_pad_as_one_piece(name):
    s = su.support([shapes()[name]], CFG)
    assert s.points > 0 and s.pillars > 0 and s.dropped == 0
    whole = mf.Manifold.batch_boolean(s.all, mf.OpType.Add)
    assert len(whole.decompose()) == 1, "something hangs loose"
    assert whole.bounding_box()[2] == pytest.approx(0.0, abs=1e-6)
    part = s.parts[0]
    assert part.bounding_box()[2] == pytest.approx(CFG.pad_thickness + CFG.elevation)
    # the supports touch the part only with the tips of their heads
    inside = (s.supports ^ part).volume()
    tip = math.pi * (0.5 * CFG.head_front) ** 2 * CFG.penetration
    assert inside < 2.0 * tip * s.points


def test_the_points_are_under_the_part():
    m = shapes()["sphere"]
    s = su.support([m], CFG)
    mesh = su.Mesh(s.parts[0])
    pts = su.support_points(s.parts[0], mesh, CFG, 0.1)
    centre = np.asarray(s.parts[0].bounding_box()[:3]) + 10.0
    assert pts and all(p.pos[2] < centre[2] - 0.5 * 10.0 * 0.5 for p in pts), \
        "a sphere needs supports only on its lower half"
    assert all(p.normal[2] < 0 for p in pts), "every point is on an underside"


def test_both_arms_of_a_t_are_supported():
    s = su.support([shapes()["T"]], CFG)
    tips = [x for x in (s.supports.slice(s.parts[0].bounding_box()[2] + 19.9).to_polygons())]
    xs = np.concatenate([np.asarray(t)[:, 0] for t in tips]) if tips else np.zeros(0)
    cx = 0.5 * (s.parts[0].bounding_box()[0] + s.parts[0].bounding_box()[3])
    assert (xs < cx - 8).any() and (xs > cx + 8).any(), "an arm hangs free"


def test_without_supports_the_part_stands_on_the_pad():
    s = su.support([shapes()["plate"]], CFG, supports_on=False)
    assert s.supports is None and s.pad is not None
    assert s.parts[0].bounding_box()[2] == pytest.approx(CFG.pad_thickness)
    whole = mf.Manifold.batch_boolean(s.all, mf.OpType.Add)
    assert len(whole.decompose()) == 1


# ------------------------------------------------------------------ hollowing

def heights(top, layer=0.5):
    """The middle of every layer of a print of `top` mm high."""
    return [(i + 0.5) * layer for i in range(int(round(top / layer)))]


def white_pixels(path, index):
    """The pixels a layer of an SL1 archive cures."""
    img = ss.read_layer(path.read_bytes(), index).convertToFormat(QImage.Format_Grayscale8)
    return int((ss._pixels(img) > 127).sum())


def test_a_30_mm_cube_becomes_a_shell_of_2_5_mm():
    cav = sh.hollow_layers(mf.Manifold.cube([30, 30, 30]), heights(30), 2.5)
    assert cav[15.25].area() == pytest.approx(25.0 ** 2, rel=0.03)
    assert not [z for z in cav if z <= 2.5], "the floor of the cavity is part of the print"
    assert not [z for z in cav if z >= 27.5], "so is its roof"


def test_the_shell_of_a_sphere_is_2_5_mm_thick_everywhere():
    sphere = mf.Manifold.sphere(15, 96).translate((0.0, 0.0, 15.0))
    zs = heights(30)
    cav = sh.hollow_layers(sphere, zs, 2.5)
    shell = (sum(sphere.slice(z).area() for z in zs)
             - sum(c.area() for c in cav.values())) * 0.5
    assert shell == pytest.approx(4.0 / 3.0 * math.pi * (15.0 ** 3 - 12.5 ** 3), rel=0.05)


def test_the_drain_holes_go_through_the_floor_of_the_cavity():
    cube = mf.Manifold.cube([30, 30, 30])
    zs = heights(30)
    hollow, cav = sh.hollowed(cube, 2.5, zs)
    bottom = min(cav)
    points, diameter = sh.drain_holes(cube, bottom, wall=2.5, zs=zs)
    assert len(points) == 2 and math.dist(points[0], points[1]) > 20.0
    assert diameter == sh.DRAIN_DIAMETER
    for x, y in points:
        probe = mf.Manifold.cylinder(bottom + 1.0, 0.02, 0.02, 16).translate((x, y, -1.0))
        plastic = mf.Manifold.batch_boolean([probe, hollow], mf.OpType.Intersect).volume()
        assert plastic == pytest.approx(0.0, abs=1e-6), "the resin inside cannot get out"


@pytest.mark.parametrize("size, area", [(10.0, 25.0), (4.0, None)])
def test_a_part_thinner_than_twice_the_wall_stays_solid(size, area):
    cav = sh.hollow_layers(mf.Manifold.cube([size] * 3), heights(size), 2.5)
    if area is None:
        assert not cav, "nothing is left of a shell of 2.5 mm in a part of 4 mm"
    else:
        middle = min(cav, key=lambda z: abs(z - 0.5 * size))
        assert cav[middle].area() == pytest.approx(area, rel=0.03)


def test_a_hollow_layer_is_drawn_with_its_cavity_and_costs_less_resin(library, tmp_path):
    pr = library.printer("Acme Resin Two")
    st = sp.ResinSettings(layer_height=0.5)
    cube = ss.place_on_plate([mf.Manifold.cube([30, 30, 30])], pr)
    cav = sh.hollow_layers(cube[0], ss.layer_heights(30.0, 0.5), 2.5)
    solid, hollow = tmp_path / "solid.sl1", tmp_path / "hollow.sl1"
    a = ss.write_sl1(str(solid), pr, None, st, cube)
    b = ss.write_sl1(str(hollow), pr, None, st, cube, cavities=cav)
    assert b.millilitres == pytest.approx(a.millilitres - 25.0 ** 2 * 25.0 / 1000.0, rel=0.01)
    middle = ss.layer_heights(30.0, 0.5).index(15.25)
    assert white_pixels(hollow, middle) < white_pixels(solid, middle)


def test_the_dialog_remembers_the_hollow_choice(library):
    from PySide6.QtWidgets import QWidget
    import volura.app as app_module
    import volura.sla_dialog as sd

    class Win(QWidget):
        def __init__(self):
            super().__init__()
            self.settings = app_module.Settings()

    win = Win()
    try:
        start = app_module.Settings()
        start.resin_hollow, start.resin_wall, start.resin_drain = False, 2.5, True
        start.save()
        dlg = sd.ResinDialog(win, library)
        assert not dlg.hollow.isChecked(), "a print is solid unless you say otherwise"
        assert not dlg.wall.isEnabled() and not dlg.drain.isEnabled()
        dlg.hollow.setChecked(True)
        dlg.wall.setValue(4.0)
        dlg.drain.setChecked(False)
        assert dlg.wall.isEnabled() and dlg.drain.isEnabled()
        assert (dlg.settings().hollow, dlg.settings().wall,
                dlg.settings().drain_holes) == (True, 4.0, False)
        assert dlg.choice()["hollow"] and dlg.choice()["wall"] == 4.0
        assert dlg.choice()["drain"] is False
    finally:
        win.close()


