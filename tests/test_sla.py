def printer(mirror_x=False, mirror_y=False):
    return sp.ResinPrinter("p", "P", "Acme", 120.0, 68.0, 600, 340, 150.0, mirror_x, mirror_y,
                           False, "goo")


# ------------------------------------------------------------------ profiles

def test_the_resin_printers_and_print_profiles_are_read(library):
    assert [p.name for p in library.printers] == ["Acme Resin One", "Acme Resin Two"]
    p = library.printer("Acme Resin One")
    assert (p.maker, p.pixels_x, p.pixels_y, p.width, p.depth) == ("Acme", 600, 340, 120.0, 68.0)
    assert p.pixel == pytest.approx((0.2, 0.2))
    assert p.mirror_x and not p.mirror_y and p.file_format == "goo" and p.extension == "goo"
    assert p.custom_values == {"LiftHeight": "6", "LiftSpeed": "90"}
    assert library.layer_heights() == [0.05, 0.1]
    prof = library.print_profile(0.06, "Light")
    assert prof.layer_height == 0.05 and prof.level == "Light"


def test_the_support_sizes_come_from_the_profile(library):
    cfg = su.SupportConfig.from_profile(library.print_profile(0.05).values, density=200.0)
    assert (cfg.head_front, cfg.pillar, cfg.elevation, cfg.density) == (0.8, 1.2, 5.0, 200.0)
    assert cfg.pad_thickness == su.PAD_MIN, "a pad too thin to come off is made thicker"


def test_influence_grows_with_height_and_shrinks_with_density():
    assert su.influence(0.0) == pytest.approx(3.2)
    assert su.influence(15.0) == pytest.approx(5.0)
    assert su.influence(100.0) == pytest.approx(6.0)
    assert su.influence(0.0, 400.0) == pytest.approx(1.6)


