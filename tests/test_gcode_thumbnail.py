"""A picture of the print in the G-code, for the screen of the printer.

`gcode_thumbnail` paints the model flat shaded in the corner of the window (`render`), puts a PNG
in the comment block a printer screen reads (`block`) and writes those blocks behind the header
comments of a G-code file (`insert`). These tests paint cubes and spheres of their own: the size
and the transparency of a picture, the colours of the parts and which part lies in front, what a
block looks like and what an insert leaves alone, the sizes File > Slice offers. The last ones
stream a thumbnail into a G-code of fifty million bytes and look at what a picture in the file
does to the print preview.

Run with:  python -m pytest tests/test_gcode_thumbnail.py
"""
import base64
import os
import sys
import time

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import manifold3d as mf  # noqa: E402
import numpy as np  # noqa: E402
import pytest  # noqa: E402
from PySide6.QtGui import QImage  # noqa: E402
from PySide6.QtWidgets import QApplication  # noqa: E402

from volura import gcode_preview, gcode_thumbnail as gt  # noqa: E402
from volura.viewcube import basis  # noqa: E402

_app = QApplication.instance() or QApplication(sys.argv[:1])

GCODE = """;FLAVOR:Marlin
;TIME:3
;Filament used: 0.05m
;Layer height: 0.2
;generated by Volura
M104 S200
G28
;LAYER:0
G1 X10 Y10 E0.5
G1 X20 Y10 E1.0
;LAYER:1
G1 Z0.4
G1 X10 Y10 E1.5
M107
"""

RED, BLUE = "#d23b3b", "#2f6fd6"


def _cube(size=20.0, at=(0.0, 0.0, 0.0)):
    """A cube of `size` mm with its middle at `at` (a cube in manifold grows from 0)."""
    m = mf.Manifold.cube((size, size, size)).translate(
        np.asarray(at, dtype=float) - 0.5 * size).to_mesh()
    return np.asarray(m.vert_properties)[:, :3], np.asarray(m.tri_verts)


def _pixels(png):
    """A PNG as (height, width, 4): red, green, blue and alpha of every pixel, 0..255."""
    img = QImage.fromData(png).convertToFormat(QImage.Format_RGBA8888)
    line = img.bytesPerLine()
    # .copy(): the bytes of a QImage are gone when the QImage is, and this array outlives it
    rows = np.frombuffer(img.constBits(), dtype=np.uint8, count=line * img.height()).copy()
    return rows.reshape(img.height(), line)[:, :img.width() * 4].reshape(
        img.height(), img.width(), 4)


def _colour(px, colour):
    """How many pixels are clearly of this ``#rrggbb``: the strongest channel of the colour is
    also well ahead of the other two in the pixel, whatever the flat shading did to it."""
    rgb = [int(colour[i:i + 2], 16) for i in (1, 3, 5)]
    at = int(np.argmax(rgb))
    got = px[..., at].astype(int)
    near = px[..., 3] > 0
    for k in range(3):
        if k != at:
            near &= got > px[..., k].astype(int) + 40
    return int(np.count_nonzero(near))


def _png_of(block):
    """The picture a block carries back: the base64 of the lines between begin and end."""
    lines = block.splitlines()
    at = int(lines[1].split()[-1])
    body = "".join(line[2:] for line in lines[2:-2])
    assert len(body) == at, "the block says another length than it carries"
    return base64.b64decode(body)


# ------------------------------------------------------------------ painting the model


def test_the_picture_is_a_png_of_the_size_asked():
    png = gt.render([_cube() + (RED,)], 300, 300)
    assert png[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    img = QImage.fromData(png)
    assert (img.width(), img.height()) == (300, 300)
    other = QImage.fromData(gt.render([_cube() + (RED,)], 313, 173))
    assert (other.width(), other.height()) == (313, 173), "the wide picture of the Prusa screen"


def test_the_model_floats_on_a_transparent_background_in_the_middle():
    px = _pixels(gt.render([_cube() + (RED,)], 300, 300))
    assert [int(px[i, j, 3]) for i, j in ((0, 0), (0, 299), (299, 0), (299, 299))] == [0, 0, 0, 0]
    assert px[150, 150, 3] >= 250, "the middle of the model is not painted"
    ys, xs = np.nonzero(px[..., 3] > 0)
    assert abs((xs.min() + xs.max()) / 2 - 150) <= 1.5, "not in the middle"
    assert abs((ys.min() + ys.max()) / 2 - 150) <= 1.5, "not in the middle"
    span = max(xs.max() - xs.min() + 1, ys.max() - ys.min() + 1)
    assert span == pytest.approx(300 * (1 - 2 * gt.MARGIN), abs=2.5), "not filled to the margin"
    assert xs.min() >= 1 and ys.min() >= 1 and xs.max() <= 298 and ys.max() <= 298, \
        "the model grows into the edge of the picture"


def test_a_part_keeps_its_own_colour():
    px = _pixels(gt.render([_cube() + (RED,)], 300, 300))
    assert _colour(px, RED) > 5000
    assert _colour(px, BLUE) == 0


def test_the_parts_of_two_colours_are_both_in_the_picture():
    png = gt.render([_cube(16.0, (-12.0, 0, 0)) + (RED,), _cube(16.0, (12.0, 0, 0)) + (BLUE,)],
                    300, 300)
    px = _pixels(png)
    assert _colour(px, RED) > 1000 and _colour(px, BLUE) > 1000
    assert px[..., 3].max() == 255


def test_a_part_behind_another_is_hidden_by_it_whatever_the_model_lists_them():
    """The parts are painted the one behind the other first, so two parts that overlap in the
    picture lie the right way round also when the model lists the front part first."""
    eye, _right, _up = basis(gt.YAW, gt.PITCH)
    back = tuple(-eye * 25.0)
    front = _cube(20.0) + (RED,)
    behind = _cube(12.0, back) + (BLUE,)     # smaller, on the line of sight behind the first
    a = gt.render([front, behind], 300, 300)
    b = gt.render([behind, front], 300, 300)
    assert a == b, "the order of the parts in the model shows in the picture"
    px = _pixels(a)
    assert _colour(px, RED) > 5000 and _colour(px, BLUE) == 0, "the part behind shows through"


def test_a_round_surface_is_painted_whole():
    """Flat shading paints a triangle next to a triangle: between two of them may not stand a
    light hairline, or the printer shows a ball of yarn with cracks in it."""
    mesh = mf.Manifold.sphere(20.0, 96).to_mesh()
    ball = (np.asarray(mesh.vert_properties)[:, :3], np.asarray(mesh.tri_verts), RED)
    alpha = _pixels(gt.render([ball], 200, 200))[..., 3]
    for line in (alpha[100], alpha[:, 100]):     # across the ball and around it
        on = np.nonzero(line > 0)[0]
        assert on.min() < 100 < on.max()
        # two pixels from each end are the soft edge of the ball itself, everything between them
        # is the surface: the antialiasing of Qt leaves a fraction of a percent at a seam, a whole
        # percent of the printer's background through a line is a crack you can see
        assert np.min(line[on.min() + 2:on.max() - 1]) >= 250, "a crack in the ball"


def test_a_flat_face_of_the_model_is_still_a_picture():
    v = np.array([(0, 0, 0), (20, 0, 0), (20, 20, 0), (0, 20, 0)], dtype=float)
    t = np.array([(0, 1, 2), (0, 2, 3)])
    png = gt.render([(v, t, RED)], 200, 200)
    px = _pixels(png)
    assert np.count_nonzero(px[..., 3] == 255) > 1000, "a wall of the drawing is not painted"
    assert _colour(px, RED) > 1000


def test_the_smallest_picture_a_printer_wants_still_shows_the_model():
    for _label, _value, chosen in gt.THUMBNAILS:
        for width, height in chosen:
            png = gt.render([_cube() + (RED,)], width, height)
            img = QImage.fromData(png)
            assert (img.width(), img.height()) == (width, height)
            assert np.count_nonzero(_pixels(png)[..., 3] == 255) > 0, _label


def test_a_model_of_two_hundred_thousand_triangles_is_painted_in_a_second_or_so():
    mesh = mf.Manifold.sphere(30.0, 640).to_mesh()
    verts, tris = np.asarray(mesh.vert_properties)[:, :3], np.asarray(mesh.tri_verts)
    assert len(tris) > 200_000
    start = time.monotonic()
    png = gt.render([(verts, tris, RED)], 300, 300)
    took = time.monotonic() - start
    assert _pixels(png)[150, 150, 3] >= 250, "the middle of the ball is not painted"
    assert took < 8.0, f"painting {len(tris)} triangles took {took:.1f} s"


def test_a_model_of_nothing_says_so():
    verts, tris = _cube()
    with pytest.raises(ValueError):
        gt.render([], 300, 300)
    with pytest.raises(ValueError):
        gt.render([(verts, np.zeros((0, 3), dtype=np.int64), RED)], 300, 300)


# ------------------------------------------------------------------ the block and its lines


def test_a_block_is_a_comment_block_of_the_right_length():
    png = gt.render([_cube() + (RED,)], 48, 48)
    text = gt.block(png, 48, 48)
    lines = text.splitlines()
    assert lines[0] == ";" and lines[-1] == ";"
    assert lines[1] == f"; thumbnail begin 48x48 {len(base64.b64encode(png))}"
    assert lines[-2] == "; thumbnail end"
    assert all(line.startswith(";") for line in lines), "a line that is no comment"
    assert all(len(line) - 2 <= gt.LINE for line in lines), "a line the printer cuts off"
    assert _png_of(text) == png
    assert text.endswith("\n")


def test_the_block_gives_the_size_it_was_asked_for():
    png = gt.render([_cube() + (RED,)], 48, 48)
    assert gt.block(png, 313, 173).splitlines()[1] == \
        f"; thumbnail begin 313x173 {len(base64.b64encode(png))}"


# ------------------------------------------------------------------ writing into a G-code


def _cut(text):
    """Where the header comments of a G-code end: the start of the first line that is one."""
    at = 0
    for line in text.splitlines(keepends=True):
        if line.strip() and not line.startswith(";"):
            break
        at += len(line)
    return at


def _write(tmp_path, text, name="print.gcode"):
    path = tmp_path / name
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)
    return path


def test_the_thumbnails_stay_behind_the_header_of_the_g_code(tmp_path):
    path = _write(tmp_path, GCODE)
    one, two = gt.block(b"png-one", 48, 48), gt.block(b"png-two", 300, 300)
    gt.insert(str(path), [one, two])
    got = path.read_text(encoding="utf-8", newline="")
    at = _cut(GCODE)
    assert got == GCODE[:at] + one + two + GCODE[at:]
    assert got.startswith(";FLAVOR:Marlin") and got.endswith("M107\n")


def test_a_g_code_that_keeps_carriage_returns_keeps_them_everywhere(tmp_path):
    """CuraEngine writes \\r\\n; a thumbnail that makes the file one big line feed is a file a
    printer no longer understands."""
    text = GCODE.replace("\n", "\r\n")
    path = _write(tmp_path, text)
    block = gt.block(b"png", 32, 32)
    gt.insert(str(path), [block])
    got = path.read_text(encoding="utf-8", newline="")
    assert got == text[:_cut(text)] + block.replace("\n", "\r\n") + text[_cut(text):]
    assert "\n\r" not in got.replace("\r\n", "<CRLF>"), "a lone line feed in the file"


def test_a_file_that_starts_with_a_command_gets_its_thumbnails_in_front_of_it(tmp_path):
    text = "G28\nG1 X10 Y10 E0.5\n"
    path = _write(tmp_path, text, "no-header.gcode")
    block = gt.block(b"png", 48, 48)
    gt.insert(str(path), [block])
    assert path.read_text(encoding="utf-8", newline="") == block + text


def test_a_file_that_is_nothing_but_a_header_still_gets_its_picture(tmp_path):
    text = ";FLAVOR:Marlin\n;no moves at all\n"
    path = _write(tmp_path, text, "empty.gcode")
    block = gt.block(b"png", 48, 48)
    gt.insert(str(path), [block])
    assert path.read_text(encoding="utf-8", newline="") == text + block


def test_nothing_to_put_in_leaves_the_file_alone(tmp_path):
    path = _write(tmp_path, GCODE)
    before, stamp = path.read_bytes(), path.stat().st_mtime_ns
    gt.insert(str(path), [])
    gt.insert(str(path), [""])
    assert path.read_bytes() == before and path.stat().st_mtime_ns == stamp


def test_the_old_g_code_is_gone_also_when_the_file_is_replaced(tmp_path):
    """The picture is written next to the file and put in its place, so a crash leaves the old
    file; nothing of it may be left behind afterwards."""
    path = _write(tmp_path, GCODE)
    gt.insert(str(path), [gt.block(b"png", 48, 48)])
    assert sorted(os.listdir(tmp_path)) == ["print.gcode"]


def test_a_big_g_code_is_copied_in_pieces_and_never_read_all_at_once(tmp_path, monkeypatch):
    """A print of many hours is tens of millions of bytes; a thumbnail may not need them in
    memory, so the rest of the file is streamed past in pieces of CHUNK."""
    path = tmp_path / "long.gcode"
    size = 50 * 1024 * 1024
    with open(path, "wb") as fh:
        fh.write(b";FLAVOR:Marlin\r\n")
        while fh.tell() < size:
            fh.write((b";LAYER:0\r\nG1 X1 Y1 E1\r\n" * 2048))
    whole = path.stat().st_size
    asked = []
    real = open

    class Reader:
        """The G-code file, counting the pieces it is read in."""

        def __init__(self, fh):
            self._fh = fh

        def __enter__(self):
            self._fh.__enter__()
            return self

        def __exit__(self, *exc):
            return self._fh.__exit__(*exc)

        def read(self, *args):
            piece = self._fh.read(*args)
            asked.append(len(piece))
            return piece

        def __getattr__(self, name):
            return getattr(self._fh, name)

    monkeypatch.setattr(gt, "open",
                        lambda name, *a, **kw: Reader(real(name, *a, **kw)), raising=False)
    gt.insert(str(path), [gt.block(b"png", 300, 300)])
    monkeypatch.undo()

    assert asked, "the file was not read at all"
    assert max(asked) <= gt.CHUNK, "a whole file was read into memory"
    assert sum(asked) > whole - 4 * gt.CHUNK, "the print itself was not copied over"
    text = path.read_text(encoding="utf-8", errors="replace")
    assert text.count("G1 X1 Y1 E1") > 1_000_000 and "; thumbnail begin 300x300" in text


# ------------------------------------------------------------------ what it does to the rest


def test_a_picture_in_the_g_code_leaves_the_print_preview_alone(tmp_path):
    """The printer screen reads the picture; the preview on the screen of the computer reads the
    moves. Both look at the same file, and the comment lines of a picture are no moves."""
    path = _write(tmp_path, GCODE)
    before = gcode_preview.read_gcode(str(path), 1.75)
    gt.insert(str(path), [gt.block(gt.render([_cube() + (RED,)], 300, 300), 300, 300)])
    after = gcode_preview.read_gcode(str(path), 1.75)
    assert len(after.layers) == len(before.layers) > 0
    assert (after.lo, after.hi, after.materials) == (before.lo, before.hi, before.materials)
    for a, b in zip(before.layers, after.layers):
        assert a.number == b.number and a.z == b.z and a.height == b.height
        for key in ("seg", "kind", "t", "width"):
            assert np.array_equal(getattr(a, key), getattr(b, key)), key


def test_the_sizes_the_thumbnail_choices_draw():
    assert gt.sizes(gt.DEFAULT) == [(48, 48), (300, 300)]
    assert gt.sizes("off") == [] and gt.sizes("") == [] and gt.sizes(None) == []
    assert gt.sizes("no such choice") == []
    assert gt.sizes("32x32/300x300") == [(32, 32), (300, 300)]
    assert gt.sizes(gt.THUMBNAILS[2][1]) == [(16, 16), (313, 173), (440, 240)]
    for label, value, chosen in gt.THUMBNAILS:
        assert gt.sizes(value) == list(chosen), label
    assert gt.THUMBNAILS[0][1] == "off", "the first choice draws nothing"
    assert gt.DEFAULT != "off" and gt.sizes(gt.DEFAULT), "what a slice draws when nothing was set"
    assert len(gt.THUMBNAILS) == len({value for _l, value, _s in gt.THUMBNAILS}) == \
        len({label for label, _v, _s in gt.THUMBNAILS}), "two choices that are the same"


def test_a_part_without_a_colour_is_grey_and_not_black():
    px = _pixels(gt.render([_cube() + (None,)], 100, 100))
    r, g, b, a = (int(v) for v in px[50, 50])
    assert a == 255 and abs(r - g) <= 2 and abs(g - b) <= 2 and r > 100, (r, g, b, a)
